-- Related contacts and who introduced whom. The company module stays the
-- organisations table; this only adds the relationship a contact can hold.

alter table public.contacts
    add column if not exists introduced_by bigint;

alter table public.contacts
    drop constraint if exists contacts_introduced_by_fkey;

alter table public.contacts
    add constraint contacts_introduced_by_fkey
    foreign key (introduced_by) references public.contacts(id) on delete set null;

create table if not exists public.contact_links (
    id bigint generated by default as identity primary key,
    contact_id bigint not null,
    related_id bigint not null,
    constraint contact_links_distinct check (contact_id <> related_id),
    constraint contact_links_pair unique (contact_id, related_id)
);

alter table public.contact_links
    drop constraint if exists contact_links_contact_id_fkey;
alter table public.contact_links
    add constraint contact_links_contact_id_fkey
    foreign key (contact_id) references public.contacts(id) on delete cascade;

alter table public.contact_links
    drop constraint if exists contact_links_related_id_fkey;
alter table public.contact_links
    add constraint contact_links_related_id_fkey
    foreign key (related_id) references public.contacts(id) on delete cascade;

alter table public.contact_links enable row level security;

drop policy if exists "Enable read access for authenticated users" on public.contact_links;
create policy "Enable read access for authenticated users" on public.contact_links
    for select to authenticated using (true);
drop policy if exists "Enable insert for authenticated users only" on public.contact_links;
create policy "Enable insert for authenticated users only" on public.contact_links
    for insert to authenticated with check (true);
drop policy if exists "Enable update for authenticated users only" on public.contact_links;
create policy "Enable update for authenticated users only" on public.contact_links
    for update to authenticated using (true) with check (true);
drop policy if exists "Contact Links Delete Policy" on public.contact_links;
create policy "Contact Links Delete Policy" on public.contact_links
    for delete to authenticated using (true);

grant all on table public.contact_links to authenticated;
grant all on table public.contact_links to service_role;
grant usage, select on sequence public.contact_links_id_seq to authenticated;
grant usage, select on sequence public.contact_links_id_seq to service_role;

create or replace view public.contacts_summary with (security_invoker = on) as
select
    co.id,
    co.first_name,
    co.last_name,
    co.gender,
    co.title,
    co.background,
    co.avatar,
    co.first_seen,
    co.last_seen,
    co.has_newsletter,
    co.status,
    co.tags,
    co.company_id,
    co.sales_id,
    co.linkedin_url,
    co.email_jsonb,
    co.phone_jsonb,
    (jsonb_path_query_array(co.email_jsonb, '$[*]."email"'))::text as email_fts,
    (jsonb_path_query_array(co.phone_jsonb, '$[*]."number"'))::text as phone_fts,
    c.name as company_name,
    count(distinct t.id) filter (where t.done_date is null) as nb_tasks,
    co.external_id,
    co.source,
    co.ask_policy,
    co.site_user_id,
    co.locked_fields,
    co.outreach_status,
    co.first_contacted_at,
    co.last_contacted_at,
    co.email_holder,
    co.contact_via,
    co.list,
    co.introduced_by,
    (
        select trim(both from concat_ws(' ', introducer.first_name, introducer.last_name))
        from public.contacts introducer
        where introducer.id = co.introduced_by
    ) as introduced_by_name
from public.contacts co
    left join public.tasks t on co.id = t.contact_id
    left join public.companies c on co.company_id = c.id
group by co.id, c.name;

create or replace function public.lock_edited_contact_fields()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  fields text[] := coalesce(new.locked_fields, '{}'::text[]);
begin
  if coalesce(current_setting('app.contact_sync', true), '') = 'on' then
    return new;
  end if;

  if new.first_name is distinct from old.first_name then
    fields := fields || array['first_name'];
  end if;
  if new.last_name is distinct from old.last_name then
    fields := fields || array['last_name'];
  end if;
  if new.title is distinct from old.title then
    fields := fields || array['title'];
  end if;
  if new.email_jsonb is distinct from old.email_jsonb then
    fields := fields || array['email'];
  end if;
  if new.company_id is distinct from old.company_id then
    fields := fields || array['company'];
  end if;
  if new.tags is distinct from old.tags then
    fields := fields || array['tags'];
  end if;
  if new.external_id is distinct from old.external_id then
    fields := fields || array['external_id'];
  end if;
  if new.ask_policy is distinct from old.ask_policy then
    fields := fields || array['ask_policy'];
  end if;
  if new.background is distinct from old.background then
    fields := fields || array['background'];
  end if;
  if new.source is distinct from old.source then
    fields := fields || array['source'];
  end if;
  if new.linkedin_url is distinct from old.linkedin_url then
    fields := fields || array['linkedin_url'];
  end if;
  if new.outreach_status is distinct from old.outreach_status then
    fields := fields || array['outreach_status'];
  end if;
  if new.first_contacted_at is distinct from old.first_contacted_at then
    fields := fields || array['first_contacted_at'];
  end if;
  if new.last_contacted_at is distinct from old.last_contacted_at then
    fields := fields || array['last_contacted_at'];
  end if;
  if new.email_holder is distinct from old.email_holder then
    fields := fields || array['email_holder'];
  end if;
  if new.contact_via is distinct from old.contact_via then
    fields := fields || array['contact_via'];
  end if;
  if new.list is distinct from old.list then
    fields := fields || array['list'];
  end if;
  if new.introduced_by is distinct from old.introduced_by then
    fields := fields || array['introduced_by'];
  end if;
  if new.status is distinct from old.status then
    fields := fields || array['status'];
  end if;

  select coalesce(array_agg(distinct value), '{}'::text[])
    into fields
  from unnest(fields) as value;

  new.locked_fields := fields;
  return new;
end;
$$;
